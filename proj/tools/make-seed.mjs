#!/usr/bin/env node
/**
 * Turns the current JSON catalog (data/*.json) into supabase/seed.sql.
 *   node tools/make-seed.mjs
 * Every item becomes a published, platform-owned row (owner_id null). Assign owners later in
 * the admin panel (admin_set_property_meta). Safe to re-run: rows are upserted by id.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const load = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, 'data', f), 'utf8'));
const lit = (v) => {
  const json = JSON.stringify(v);
  if (json.includes('$ds$')) throw new Error('catalog contains the dollar-quote tag $ds$');
  return `$ds$${json}$ds$::jsonb`;
};
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const out = ['-- GENERATED by tools/make-seed.mjs from data/*.json — do not edit by hand.', 'begin;', ''];

const KINDS = [['hotels.json', 'hotel'], ['excursions.json', 'excursion'], ['transfers.json', 'transfer'], ['restaurants.json', 'restaurant']];
let n = 0;
for (const [file, kind] of KINDS) {
  load(file).forEach((item, i) => {
    if (!item || typeof item.id !== 'string') throw new Error(`${file}[${i}] has no string id`);
    out.push(`insert into public.properties (id, kind, status, sort_order, data) values (${q(item.id)}, '${kind}', 'published', ${(i + 1) * 10}, ${lit(item)})
  on conflict (id) do update set data = excluded.data, sort_order = excluded.sort_order;`);
    n++;
  });
}

const CONTENT = [['destinations.json', 'destination'], ['articles.json', 'article'], ['promoSlides.json', 'promo_slide'], ['reviews.json', 'testimonial']];
for (const [file, kind] of CONTENT) {
  load(file).forEach((item, i) => {
    if (!item || typeof item.id !== 'string') throw new Error(`${file}[${i}] has no string id`);
    const published = kind === 'promo_slide' ? item.active !== false : true;
    out.push(`insert into public.site_content (kind, id, sort_order, published, data) values ('${kind}', ${q(item.id)}, ${(i + 1) * 10}, ${published}, ${lit(item)})
  on conflict (kind, id) do update set data = excluded.data, sort_order = excluded.sort_order, published = excluded.published;`);
    n++;
  });
}
out.push('', 'commit;', '');
fs.writeFileSync(path.join(ROOT, 'supabase', 'seed.sql'), out.join('\n'));
console.log(`supabase/seed.sql written: ${n} rows`);
