#!/usr/bin/env node
/**
 * Turns the OLD bookings (Firebase Realtime Database export) into SQL for Supabase.
 *
 *   1. Export in Firebase console:  Realtime Database → ⋮ → Export JSON   (needs the /allBookings node)
 *   2. Import your users FIRST (supabase-community/firebase-to-supabase keeps e-mail + password hashes),
 *      so every customer already has a profile. Bookings are linked by e-mail.
 *   3. node tools/import-firebase-bookings.mjs firebase-export.json > supabase/import-bookings.sql
 *   4. Run supabase/import-bookings.sql in the SQL editor (one transaction; re-runnable: existing ids are skipped).
 *
 * Unpaid checkout sessions (/pendingBookings) are never imported. Rows that can not be mapped are listed on stderr.
 */
import fs from 'node:fs';

const src = JSON.parse(fs.readFileSync(process.argv[2] || 'firebase-export.json', 'utf8'));
const all = src.allBookings || src;                       // accept either the whole export or just the node
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const lit = (v) => { const j = JSON.stringify(v); if (j.includes('$ds$')) throw new Error('unsupported content'); return `$ds$${j}$ds$::jsonb`; };
const num = (v, d = 0) => (Number.isFinite(Number(v)) ? Number(v) : d);
const ts = (v) => { const d = new Date(v); return Number.isNaN(d.getTime()) ? null : d.toISOString(); };
const day = (v) => (/^\d{4}-\d{2}-\d{2}$/.test(String(v || '')) ? String(v) : null);
const KIND_ID = { hotel: 'hotelId', excursion: 'excursionId', transfer: 'transferId' };
const STATUS = { completed: 'completed', cancelled: 'cancelled', refunded: 'refunded', failed: 'failed' };
const DROP = ['uid', 'ownerUid', 'status', 'createdAt', 'earning', 'ownerStatus', 'ownerNote', 'adminNote', 'cancelledAt', 'cancelledBy', 'cancelReason', 'needsRefund', 'card', 'cardNumber', 'cvv', 'cvc', 'expiry'];

const out = ['-- GENERATED by tools/import-firebase-bookings.mjs', 'begin;'];
let ok = 0; const skipped = [];
for (const [id, b] of Object.entries(all)) {
  const kind = b && b.type;
  const status = STATUS[b && b.status];
  if (!/^[A-Za-z0-9_-]{3,64}$/.test(id) || !KIND_ID[kind] || !status) { skipped.push(`${id}: unsupported type/status (${kind}/${b && b.status})`); continue; }
  const total = num(b.total);
  if (total <= 0 || !b.email) { skipped.push(`${id}: no total or no e-mail`); continue; }
  const rate = kind === 'hotel' ? 0.10 : 0.05;
  const subtotal = num(b.subtotal, Math.round(total / (1 + rate)));
  const taxes = num(b.taxes, total - subtotal);
  const deposit = num(b.depositAmount, Math.round(total / 2));
  const due = num(b.amountDueNow, total);
  const e = b.earning || null;
  const data = Object.fromEntries(Object.entries(b).filter(([k]) => !DROP.includes(k)));
  const item = b[KIND_ID[kind]];
  out.push(`insert into public.bookings (id, user_id, property_id, owner_id, kind, status, payment_plan, currency, subtotal, taxes, total, deposit_amount, remaining_amount, amount_due_now,
  check_in, check_out, service_date, nights, guest_name, guest_email, guest_phone, data, reviewed, owner_status, owner_note, admin_note, needs_refund, earned_at, commission_rate, commission_amount, owner_amount, earning_void,
  cancelled_at, cancel_reason, confirmed_at, created_at)
select ${q(id)}, (select id from public.profiles where lower(email) = lower(${q(b.email)})), p.id, p.owner_id, '${kind}', '${status}', ${q(b.paymentPlan === 'deposit' ? 'deposit' : 'full')}, 'EGP',
  ${subtotal}, ${taxes}, ${total}, ${deposit}, ${num(b.remainingAmount, 0)}, ${due},
  ${day(b.checkin) ? q(day(b.checkin)) : 'null'}, ${day(b.checkout) ? q(day(b.checkout)) : 'null'}, ${day(b.date) ? q(day(b.date)) : 'null'}, ${b.nights ? num(b.nights) : 'null'},
  ${q(b.name || '')}, ${q(b.email)}, ${q(b.phone || '')}, ${lit(data)}, ${b.reviewed ? 'true' : 'false'},
  ${['confirmed', 'done', 'no_show'].includes(b.ownerStatus) ? q(b.ownerStatus) : 'null'}, ${b.ownerNote ? q(String(b.ownerNote).slice(0, 1000)) : 'null'}, ${b.adminNote ? q(String(b.adminNote).slice(0, 1000)) : 'null'}, ${b.needsRefund ? 'true' : 'false'},
  ${e && ts(e.at) ? q(ts(e.at)) : 'null'}, ${e ? num(e.rate) / 100 : 'null'}, ${e ? num(e.commission) : 'null'}, ${e ? num(e.net) : 'null'}, ${e && e.void ? 'true' : 'false'},
  ${ts(b.cancelledAt) ? q(ts(b.cancelledAt)) : 'null'}, ${b.cancelReason ? q(String(b.cancelReason).slice(0, 1000)) : 'null'}, ${ts(b.createdAt) ? q(ts(b.createdAt)) : 'null'}, ${ts(b.createdAt) ? q(ts(b.createdAt)) : 'now()'}
from (select 1) x left join public.properties p on p.id = ${q(item || '')}
on conflict (id) do nothing;`);
  ok++;
}
out.push('commit;', `-- ${ok} bookings, ${skipped.length} skipped`);
process.stdout.write(out.join('\n') + '\n');
for (const s of skipped) console.error('skipped ' + s);
console.error(`${ok} bookings written, ${skipped.length} skipped`);
