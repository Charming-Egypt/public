#!/usr/bin/env node
/**
 * Builds the two files you paste into the Supabase SQL Editor after supabase/reset/00_wipe_everything.sql:
 *   supabase/reset/01_install_schema.sql  every migration, in order, as ONE script (all tables / functions / RLS / storage / cron)
 *   supabase/reset/02_seed_minimal.sql    only what the running site needs: the catalog rows in `properties`
 *                                         (the old seed.sql also loaded `site_content` — destinations, articles, slides, testimonials —
 *                                          which now live in shared/data/*.json, so that part is dropped)
 * Re-run after adding a migration:  node tools/make-install-sql.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SQL = path.join(ROOT, 'supabase');
const mig = fs.readdirSync(path.join(SQL, 'migrations')).filter(f => f.endsWith('.sql')).sort();

const head = (title) => `-- ${'='.repeat(110)}\n-- ${title}\n-- ${'='.repeat(110)}\n`;
let install = head('Discover Sharm — full schema install (generated by tools/make-install-sql.mjs; do not edit by hand)\n-- Run once, right after 00_wipe_everything.sql. It is one transaction in the SQL Editor: any error rolls everything back.\n-- Order: ' + mig.join(' → '));
for (const f of mig) install += `\n\n${head('migration: ' + f)}${fs.readFileSync(path.join(SQL, 'migrations', f), 'utf8').trim()}\n`;
fs.writeFileSync(path.join(SQL, 'reset', '01_install_schema.sql'), install);

// seed: keep only `insert into public.properties …` statements (each is 2 lines: the insert + its `on conflict` line)
const lines = fs.readFileSync(path.join(SQL, 'seed.sql'), 'utf8').split('\n');
const keep = [];
for (let i = 0; i < lines.length; i++) {
  if (lines[i].startsWith('insert into public.properties')) keep.push(lines[i], lines[i + 1]);
}
const seed = head('Minimal operational data — catalog rows only (generated by tools/make-install-sql.mjs)\n-- platform_settings / site_settings are created by 01_install_schema.sql; nothing else is needed to run the site.') +
  `begin;\n\n${keep.join('\n')}\n\ncommit;\n\nselect kind, count(*) as items from public.properties group by kind order by kind;\n`;
fs.writeFileSync(path.join(SQL, 'reset', '02_seed_minimal.sql'), seed);
console.log(`install: ${mig.length} migrations · seed: ${keep.length / 2} catalog rows`);
