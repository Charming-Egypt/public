#!/usr/bin/env node
/**
 * Rebuild the `properties` table from the private GitHub data repo — the real source of truth for items.
 *
 * Why: bookings are priced by the DATABASE (compute_booking_price reads properties.data), but visitors see the price from the GitHub files.
 * After a wipe, rows seeded from the repo's old bundled catalog no longer match what the site shows → "Payment error: price changed".
 * This script writes one upsert per item file, with exactly the projection the content Worker stores (name/title/category/price/rooms/
 * unavailableDates), plus owner, status, featured and sort order from the file itself. Nothing is sent anywhere: it only writes a .sql file.
 *
 * Usage (either source):
 *   node tools/rebuild-db-from-github.mjs --dir ../my-data-repo            (a local clone — the folder that contains api/, or api/ itself)
 *   GITHUB_TOKEN=ghp_… node tools/rebuild-db-from-github.mjs --repo owner/data-repo [--branch main]
 *   options: --out supabase/reset/02b_properties_from_github.sql
 * Then run the .sql in the Supabase SQL Editor (after 01_install_schema.sql; use it INSTEAD of 02_seed_minimal.sql).
 * Owners: an owner uuid is kept only if that account still exists in public.profiles (otherwise the item is platform-owned — re-assign it in the console).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATS, PRICING_KEYS } from '../workers/content-worker.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const KINDS = ['hotel', 'excursion', 'transfer', 'restaurant'];
const args = process.argv.slice(2);
const opt = (n, d = '') => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : d; };
const dirArg = opt('--dir'), repo = opt('--repo'), branch = opt('--branch', 'main'), token = process.env.GITHUB_TOKEN || '';
const outFile = path.resolve(opt('--out', path.join(ROOT, 'supabase/reset/02b_properties_from_github.sql')));
if (!dirArg && !repo) { console.error('Pass --dir <local clone> or --repo owner/name (with GITHUB_TOKEN).'); process.exit(1); }

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i, ID_RE = /^[A-Za-z0-9_-]{1,64}$/;
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const lit = (v) => { const j = JSON.stringify(v); if (j.includes('$ds$')) throw new Error('item contains the dollar-quote tag $ds$'); return `$ds$${j}$ds$::jsonb`; };
const pick = (o) => { const r = {}; for (const k of PRICING_KEYS) if (o[k] !== undefined) r[k] = o[k]; return r; };

/** -> { [dir]: { files: {name: text} } } for each category folder */
async function readLocal() {
  let base = path.resolve(dirArg); if (fs.existsSync(path.join(base, 'api'))) base = path.join(base, 'api');
  const out = {};
  for (const kind of KINDS) {
    const d = path.join(base, CATS[kind].dir), files = {};
    if (fs.existsSync(d)) for (const f of fs.readdirSync(d)) if (f.endsWith('.json')) files[f] = fs.readFileSync(path.join(d, f), 'utf8');
    out[kind] = files;
  }
  return out;
}
async function readRemote() {
  const H = { Accept: 'application/vnd.github+json', 'User-Agent': 'ds-rebuild', ...(token ? { Authorization: `Bearer ${token}` } : {}) };
  const t = await fetch(`https://api.github.com/repos/${repo}/git/trees/${encodeURIComponent(branch)}?recursive=1`, { headers: H });
  if (!t.ok) { console.error('GitHub said', t.status, (await t.text()).slice(0, 200)); process.exit(1); }
  const tree = (await t.json()).tree || [], out = {};
  for (const kind of KINDS) {
    const pre = `api/${CATS[kind].dir}/`, files = {};
    const names = tree.filter(n => n.type === 'blob' && n.path.startsWith(pre) && n.path.endsWith('.json') && !n.path.slice(pre.length).includes('/'));
    for (const n of names) {
      const r = await fetch(`https://api.github.com/repos/${repo}/contents/${n.path}?ref=${encodeURIComponent(branch)}`, { headers: { ...H, Accept: 'application/vnd.github.raw+json' } });
      if (r.ok) files[n.path.slice(pre.length)] = await r.text(); else console.error('skip', n.path, r.status);
    }
    out[kind] = files;
  }
  return out;
}

const src = dirArg ? await readLocal() : await readRemote();
const lines = ['-- GENERATED by tools/rebuild-db-from-github.mjs — the items as they are in the GitHub data repo. Run after 01_install_schema.sql.', 'begin;', ''];
let n = 0; const seen = {};
for (const kind of KINDS) {
  const files = src[kind], dir = CATS[kind].dir; seen[kind] = 0;
  for (const [name, text] of Object.entries(files)) {
    if (name === `${dir}.json` || name.endsWith('.draft.json')) continue;           // the published index and pending owner edits are not items
    let it; try { it = JSON.parse(text); } catch { console.error('skip (not JSON):', dir + '/' + name); continue; }
    const id = name.replace(/\.json$/, '');
    if (!ID_RE.test(id) || !it || typeof it !== 'object') { console.error('skip:', dir + '/' + name); continue; }
    const owner = typeof it.ownerId === 'string' && UUID.test(it.ownerId) ? `(select id from public.profiles where id = ${q(it.ownerId)})` : 'null';
    const status = it.published === true ? 'published' : 'draft';
    const hasDraft = Object.prototype.hasOwnProperty.call(files, `${id}.draft.json`);
    const created = it.createdAt && !isNaN(Date.parse(it.createdAt)) ? q(new Date(it.createdAt).toISOString()) : 'now()';
    const sort = Number.isFinite(Number(it.sortOrder)) ? Math.trunc(Number(it.sortOrder)) : 1000;
    lines.push(`insert into public.properties (id, kind, owner_id, status, featured, sort_order, has_draft, created_at, data)\n  values (${q(id)}, '${kind}', ${owner}, '${status}', ${it.featured === true}, ${sort}, ${hasDraft}, ${created}, ${lit(pick(it))})\n  on conflict (id) do update set kind = excluded.kind, owner_id = excluded.owner_id, status = excluded.status, featured = excluded.featured,\n    sort_order = excluded.sort_order, has_draft = excluded.has_draft, data = excluded.data;`);
    n++; seen[kind]++;
  }
}
lines.push('', 'commit;', '', 'select kind, status, count(*) as items from public.properties group by 1, 2 order by 1, 2;', '');
fs.writeFileSync(outFile, lines.join('\n'));
console.log(`wrote ${path.relative(process.cwd(), outFile)} — ${n} items`, seen);
