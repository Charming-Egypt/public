// Builds shared/icons.css from tools/icons/set.mjs: every icon becomes a CSS mask painted with the brand gradient.
// Run: node tools/make-icons.mjs   (also run by the build)
import fs from 'node:fs'; import path from 'node:path';
import { ICONS } from './icons/set.mjs';
const root = path.join(path.dirname(new URL(import.meta.url).pathname), '..');
const attr = (a) => `fill="none" stroke="#000" stroke-linecap="round" stroke-linejoin="round" ${a}`;
const asEls = (d) => (d.trim().startsWith('<') ? d : `<path d="${d}"/>`);
function svg(ic) {
  const tf = ic.tf ? ` transform="${ic.tf}"` : '';
  const F = ic.F ? `<g fill="#000" stroke="#000" stroke-width="1.2" stroke-linejoin="round"${tf}>${ic.F.trim().startsWith('<') ? ic.F : `<path d="${ic.F}"/>`}${ic.FX || ''}</g>` : '';
  let body;
  if (ic.K) body = `<defs><mask id="k" maskUnits="userSpaceOnUse" x="0" y="0" width="24" height="24"><rect width="24" height="24" fill="#fff"/><g ${attr('stroke-width="1.7"')}${tf}>${asEls(ic.K)}</g></mask></defs><g mask="url(#k)">${F}</g>`;
  else body = F;
  const S = ic.S ? `<g ${attr(`stroke-width="${ic.w || 2.4}"`)}>${asEls(ic.S)}</g>` : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">${body}${S}</svg>`;
}
const enc = (s) => 'url("data:image/svg+xml,' + s.replace(/"/g, "'").replace(/%/g, '%25').replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E').replace(/\s+/g, ' ') + '")';
const names = Object.keys(ICONS).filter(n => ICONS[n]);
const sel = (suffix = '') => names.map(n => `:is(.fa-solid,.fa-regular,.fa-brands).fa-${n}${suffix}`).join(',\n');
let css = `/* AUTO-GENERATED by tools/make-icons.mjs — do not edit. Discover Sharm icon set: solid rounded glyphs painted with the brand gradient. */
:root { --ico-a: #ffc21a; --ico-b: #ff5b14; }
${sel()} { display: inline-block; width: 1em; height: 1em; line-height: 1; vertical-align: -.14em; font-size: inherit; flex-shrink: 0; }
${sel('::before')} { content: "" !important; display: block; width: 100%; height: 100%; background: linear-gradient(135deg, var(--ico-a), var(--ico-b)); -webkit-mask: var(--i) center / contain no-repeat; mask: var(--i) center / contain no-repeat; }
`;
for (const n of names) css += `.fa-${n}{--i:${enc(svg(ICONS[n]))}}\n`;
css += `
/* icons that carry their own colour (white / gold / red / green text utilities) stay flat so meaning is kept */
:is(.fa-solid,.fa-regular,.fa-brands)[class*="text-white"], :is(.fa-solid,.fa-regular,.fa-brands)[class*="text-gold"], :is(.fa-solid,.fa-regular,.fa-brands)[class*="text-red"], :is(.fa-solid,.fa-regular,.fa-brands)[class*="text-green"],
:is(.fa-solid,.fa-regular,.fa-brands)[class*="text-emerald"], :is(.fa-solid,.fa-regular,.fa-brands)[class*="text-yellow"], :is(.fa-solid,.fa-regular,.fa-brands)[class*="text-amber"], :is(.fa-solid,.fa-regular,.fa-brands)[class*="text-ink"],
:is(.fa-solid,.fa-regular,.fa-brands)[class*="text-violet"], :is(.fa-solid,.fa-regular,.fa-brands)[class*="text-orange"] { --ico-a: currentColor; --ico-b: currentColor; }
/* on gold / orange surfaces the glyph is dark ink, or white on solid brand colours */
.btn-gold, .btn-gold *, .gold-surface, .gold-surface * { --ico-a: #1b1206; --ico-b: #1b1206; }
.pt-cta-btn, .pt-cta-btn *, .pt-contract a, .pt-contract a *, .pt-num, .pt-num *, .em-call, .em-call *, .pt-status .pt-cta-btn * { --ico-a: #fff; --ico-b: #fff; }
.bottom-nav .nav-item, .bottom-nav .nav-item * { --ico-a: #ffd25a; --ico-b: #ff7a2a; }
.em-ico, .em-ico * { --ico-a: var(--em); --ico-b: var(--em); }
.nav-home-logo, .nav-home-logo * { --ico-a: #fff; --ico-b: #fff; }
.fa-spin { animation: ds-spin 1s linear infinite; }
@keyframes ds-spin { to { transform: rotate(360deg); } }
`;
// glyphs on brand-orange surfaces: found automatically from shared/style.css (any rule whose background is an orange/amber) so the icon never blends into its own button
{
  const style = fs.readFileSync(path.join(root, 'shared', 'style.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  const ORANGE = /background(?:-color|-image)?\s*:[^;{}]*#(?:fbbf24|fdba74|ff6b35|ffa62b|fcd34d|f59e0b|fb923c|f97316|d97706|c2410c|ea580c|ff7a2a|e8590c|ffb347|fbbf2[0-9a-f]|f5a623)\b/i;
  const DARK = /(?:^|[;\s])color\s*:\s*(?:#(?:0|1)[0-9a-f]{2,5}\b|#000\b|var\(--ink|black)/i;
  const ink = new Set(), white = new Set();
  for (const m of style.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    if (!ORANGE.test(m[2])) continue;
    const dark = DARK.test(m[2]);
    for (let sel of m[1].split(',')) {
      sel = sel.trim().replace(/:(hover|active|focus|focus-visible|disabled)\b/g, '');
      if (!sel || sel.includes('::') || sel.startsWith('@') || sel.startsWith(':root') || /^(html|body)\b/.test(sel)) continue;
      (dark ? ink : white).add(sel);
    }
  }
  const both = (set, col) => set.size ? `${[...set].map(x => `${x}, ${x} *`).join(',\n')} { --ico-a: ${col}; --ico-b: ${col}; }\n` : '';
  css += `/* auto: icons on orange surfaces (from style.css) */\n` + both(white, '#fff') + both(ink, '#1b1206');
}
fs.writeFileSync(path.join(root, 'shared', 'icons.css'), css);
console.log(`icons.css: ${names.length} icons, ${(css.length / 1024).toFixed(0)} KB`);
export { names };
